#!/usr/bin/env node
/**
 * One SQL file that builds a FRESH Wivo database from sql/000 … the newest,
 * for pasting into a new Supabase project's SQL editor (the test project).
 *
 *   TEST_SERVICE_ROLE_KEY=eyJ... node scripts/fresh-schema.mjs > fresh.sql
 *
 * The two manual edits a person makes when pasting migrations one by one are
 * made here, so the whole thing runs in one go:
 *  - sql/052 and sql/056 refuse to run until a service-role key is pasted in;
 *    this inserts THIS project's key (never production's — the script refuses
 *    a key whose project ref is production's).
 *  - sql/052 schedules the hourly invoice sender with the PRODUCTION function
 *    URL written into it. A test database must never call production, so the
 *    file ends by unscheduling it again.
 *
 * Same ordering and the same edits as the PGlite replay that runs on every
 * `npm test` (sql/test/harness.ts), so what this produces is what is tested.
 */
import { readdirSync, readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PROD_REF = 'wrtucsfmpbwekugzzzxw'
const key = process.env.TEST_SERVICE_ROLE_KEY ?? ''
if (!/^eyJ/.test(key)) {
  console.error('Set TEST_SERVICE_ROLE_KEY to the TEST project\'s service-role key (starts with eyJ).')
  process.exit(2)
}
try {
  const payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString())
  if (payload.ref === PROD_REF) { console.error('That is the PRODUCTION key. Refusing.'); process.exit(2) }
  if (payload.role !== 'service_role') { console.error(`That key's role is "${payload.role}", not service_role.`); process.exit(2) }
} catch {
  console.error('Could not read the key. Paste the service_role JWT as it is.')
  process.exit(2)
}

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'sql')
const files = readdirSync(dir).filter(f => /^\d{3}_.*\.sql$/.test(f)).sort()

let out = `-- Wivo: fresh schema, ${files[0]} … ${files.at(-1)} (${files.length} files)\n`
out += '-- Generated by scripts/fresh-schema.mjs. Paste into the TEST project\'s SQL editor and run once.\n\n'
for (const f of files) {
  out += `\n-- ═══ ${f} ${'═'.repeat(Math.max(3, 70 - f.length))}\n`
  out += readFileSync(join(dir, f), 'utf8').replaceAll('<SERVICE_ROLE_KEY>', key)
  out += '\n'
}
out += `
-- ═══ test project only ══════════════════════════════════════════════════
-- sql/052 scheduled the invoice sender against the PRODUCTION function URL.
select cron.unschedule('wivo-send-invoices') where exists (select 1 from cron.job where jobname = 'wivo-send-invoices');
notify pgrst, 'reload schema';
`
process.stdout.write(out)
